CREATE TABLE IF NOT EXISTS items(
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  kind TEXT NOT NULL CHECK(kind IN('plugin','mod','map')),
  name TEXT NOT NULL, descr TEXT NOT NULL, cat TEXT NOT NULL DEFAULT '', link TEXT NOT NULL DEFAULT '',
  img_key TEXT, file_key TEXT, file_name TEXT, file_size INTEGER NOT NULL DEFAULT 0,
  featured INTEGER NOT NULL DEFAULT 0, downloads INTEGER NOT NULL DEFAULT 0,
  ready INTEGER NOT NULL DEFAULT 0, created INTEGER NOT NULL);
CREATE INDEX IF NOT EXISTS items_kind ON items(kind, ready, created DESC);
CREATE TABLE IF NOT EXISTS sessions(sid TEXT PRIMARY KEY, csrf TEXT NOT NULL, exp INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS attempts(ip TEXT PRIMARY KEY, n INTEGER NOT NULL, t INTEGER NOT NULL);
